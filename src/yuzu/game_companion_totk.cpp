// Scenes come from Loader::TearsOfTheKingdomSceneFromRomFSPath: the name of the scene parameters the
// game loads. Shrines are Dungeon000 to Dungeon151; the open world, the prologue and the title
// screen have no card.
const Entry* TearsOfTheKingdomEntryForScene(std::string_view scene) {
    struct SceneEntry {
        std::string_view scene;
        std::string_view entry;
    };
    static constexpr SceneEntry temples[] = {
        {"LargeDungeonFire", "fire_temple"},
        {"LargeDungeonHyruleCastle", "hyrule_castle"},
        {"LargeDungeonSoul", "spirit_temple"},
        {"LargeDungeonThunder", "lightning_temple"},
        {"LargeDungeonWater", "water_temple"},
        {"LargeDungeonWind", "wind_temple"},
    };
    if (scene.starts_with("Dungeon")) {
        return FindEntry(TearsOfTheKingdom(), "shrines_of_light");
    }
    for (const auto& mapping : temples) {
        if (scene == mapping.scene) {
            return FindEntry(TearsOfTheKingdom(), mapping.entry);
        }
    }
    return nullptr;
}

