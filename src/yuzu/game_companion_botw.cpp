// Scenes come from Loader::BreathOfTheWildSceneFromRomFSPath: "Dungeon" plus the shrine number for
// a shrine, the pack name for a Divine Beast, and "MainField" for the open world, which has no card.
const Entry* BreathOfTheWildEntryForScene(std::string_view scene) {
    struct SceneEntry {
        std::string_view scene;
        std::string_view entry;
    };
    static constexpr SceneEntry beasts[] = {
        {"RemainsElectric", "vah_naboris"},
        {"RemainsFire", "vah_rudania"},
        {"RemainsWater", "vah_ruta"},
        {"RemainsWind", "vah_medoh"},
    };
    if (scene.starts_with("Dungeon")) {
        return FindEntry(BreathOfTheWild(), "shrines");
    }
    for (const auto& mapping : beasts) {
        if (scene == mapping.scene) {
            return FindEntry(BreathOfTheWild(), mapping.entry);
        }
    }
    return nullptr;
}

